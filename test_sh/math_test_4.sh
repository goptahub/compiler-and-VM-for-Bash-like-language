res=0

(( res = (1500 * 2000) / 100 + (1024 * 1024) % 1000000 - 123456 ))

echo $res

# Выражение: (1500 * 2000) / 100 + (1024 * 1024) % 1000000 - 123456
# Шаги: 
# 1) 1500 * 2000 = 3000000
# 2) 3000000 / 100 = 30000
# 3) 1024 * 1024 = 1048576
# 4) 1048576 % 1000000 = 48576
# 5) 30000 + 48576 = 78576
# 6) 78576 - 123456 = -44880

# ОТВЕТ: res = -44880