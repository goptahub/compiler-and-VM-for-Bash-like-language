# nested_test_2.sh
base=2
power=5
res=1

if (( power > 0 )); then
    i=0
    while (( i < power )); do
        (( res = res * base ))
        (( i = i + 1 ))
    done
else
    res=1
fi

echo $res

# Выражение: Вычисление 2 в степени 5, только если степень больше 0.
# Шаги:
# Условие power > 0 выполняется (5 > 0).
# Запускается цикл от i=0 до i=4 (5 итераций).
# res последовательно умножается на 2: 1 -> 2 -> 4 -> 8 -> 16 -> 32.
# Ветка else полностью игнорируется.

# ОТВЕТ: res = 32