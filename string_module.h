#ifndef STRING_MODULE_H
#define STRING_MODULE_H

/**
 * Создаёт строку формата "_n", где n — порядковый номер (начиная с 1).
 * Указатель на строку сохраняется во внутреннем массиве.
 * При заполнении массива его размер удваивается (начальная ёмкость — 32).
 * Возвращает указатель на динамически выделенную строку или NULL при ошибке.
 */
char* create_string(char* str, unsigned int num);
char* create_string_s(char* str, unsigned int num);
/**
 * Освобождает все строки, хранящиеся в массиве, а затем освобождает память,
 * выделенную под сам массив. Внутренние счётчики сбрасываются.
 * После вызова массив становится пустым и готов к новому использованию.
 */
void free_all_strings(void);

#endif